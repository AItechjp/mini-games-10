import assert from 'node:assert/strict';
import {parseKantoIndex,parseKantoDetail,parseInpit,collect,KANTO,INPIT,japaneseDate} from '../supabase/functions/commons-phone/core.mjs';
import {matches,normalizeQuery,chooseItems} from '../commons/phone-watch/search.mjs';
const at='2026-09-14T00:00:00.000Z',url='https://lfb.mof.go.jp/kantou/kinyuu/pagekt_cnt_20260612950.html';
const detail='<h1>無登録で貸金業を行っている者等について</h1><table><tr><th>電話番号等</th><td>03-6709-45××（電話） 050-3588-43××（ファクス）</td></tr></table><footer>電話048-600-1151</footer>';
const items=parseKantoDetail(detail,url,'2026-06-26',at);
assert.deepEqual(items.map(x=>x.number),['03-6709-45××']);
assert.equal(items[0].numberType,'masked');
const index='<h1>悪質な貸金業者の情報</h1><table><tr><td><a href="'+url+'">株式会社DATA</a></td><td>電話</td><td>なし</td><td>令和8年6月26日</td></tr><tr><td>1464</td><td>電話：050-6868-94×× ファクス：050-3588-43××</td><td>番号詐称</td><td>FAX</td><td>備考</td><td>令和6年2月14日</td></tr></table><footer>電話048-600-1111</footer>';
assert.equal(parseKantoIndex(index,at).details[0].url,url);
assert.deepEqual(parseKantoIndex(index,at).items.map(x=>x.number),['050-6868-94××']);
assert.equal(parseKantoIndex(index.replace(url,'https://attacker.example/'),at).details.length,0);
assert.equal(japaneseDate('令和８年６月２６日'),'2026-06-26');
const inp='<h1>旧電話番号を利用した特殊詐欺</h1>06-6110-5746 現在の相談窓口06-6444-2300';
assert.deepEqual(parseInpit(inp,at).map(x=>x.number),['06-6110-5746']);
assert.throws(()=>parseInpit(inp.replace('06-6110-5746','掲載を取り消しました'),at));
assert.equal(normalizeQuery('＋８１ ６-６１１０-５７４６'),'0661105746');
assert.equal(matches(items[0],'03-6709-4512'),true);
assert.equal(matches(items[0],'03-6708-4512'),false);
assert.equal(matches(items[0],'03367094512'),false);
assert.equal(matches(items[0],'文字だけ'),false);
assert.equal(matches({number:'090-12××-3456',numberType:'masked'},'3456'),true);
assert.equal(chooseItems(items,{filter:'full'}).length,0);
const fixture=async u=>new Response(u===KANTO?index:u===INPIT?inp:detail,{headers:{'content-type':'text/html'}});
const current=await collect(null,fixture);
assert.equal(current.items.length,3);
assert.equal(current.sources.every(s=>s.status==='ok'),true);
const failed=await collect(current,async()=>new Response('unavailable',{status:503}));
assert.equal(failed.items.length,3);
assert.equal(failed.items.every(x=>x.stale),true);
assert.equal(failed.items.find(x=>x.number==='06-6110-5746').checkedAt,current.items.find(x=>x.number==='06-6110-5746').checkedAt);
const changed=await collect(current,async u=>u===INPIT?new Response(inp.replace('06-6110-5746','削除'),{headers:{'content-type':'text/html'}}):fixture(u));
assert.equal(changed.items.find(x=>x.number==='06-6110-5746').stale,true);
console.log('Phone Watch: verified scoped extraction, FAX/contact exclusions, masked matches, query normalization, source failure and original timestamp retention.');
