import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES?require(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES+'/playwright'):await import('playwright');
const base=process.env.USAGE_BASE_URL||'http://127.0.0.1:4173/';
const browser=await chromium.launch({headless:true,...(process.env.USAGE_CHROME?{executablePath:process.env.USAGE_CHROME}:{})});
await mkdir('test-output/usage',{recursive:true});
try{
 const context=await browser.newContext(),page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/rest/v1/resource_usage_public?**',route=>route.fulfill({json:[{database_bytes:40_000_000,storage_bytes:0,storage_objects:0,checked_at:new Date().toISOString()}]}));
 await page.route('https://api.github.com/**',route=>route.fulfill({json:{workflow_runs:[{status:'completed',conclusion:'success',updated_at:new Date().toISOString()}]}}));
 await page.setViewportSize({width:1365,height:1000});
 await page.goto(new URL('commons/usage/',base).href);
 await page.waitForFunction(()=>document.getElementById('measured-count')?.textContent==='3 / 3');
 assert.equal(await page.locator('[data-metric]').count(),10);
 assert.match(await page.locator('[data-metric=db]').innerText(),/残り 460 MB/);
 assert.match(await page.locator('[data-metric=storage]').innerText(),/参考残量 1 GB/);
 assert.match(await page.locator('[data-metric=edge]').innerText(),/残量を確認できません/);
 await page.screenshot({path:'test-output/usage/desktop.png',fullPage:true});
 await page.locator('[data-edit=edge]').click();
 await page.locator('#manual-value').fill('600000');
 const now=new Date(),from=new Date(+now-86400000).toISOString().slice(0,10),to=new Date(+now+7*86400000).toISOString().slice(0,10);
 await page.locator('#period-start').fill(from);await page.locator('#period-end').fill(to);
 await page.getByRole('button',{name:'保存して残量を計算'}).click();
 assert.match(await page.locator('[data-metric=edge]').innerText(),/上限超過 100,000 回/);
 assert.equal(await page.locator('#warning-count').innerText(),'1');
 await page.locator('[data-edit=edge]').click();await page.keyboard.press('Escape');
 assert.equal(await page.locator('#manual-dialog').evaluate(d=>d.open),false);
 await page.reload();await page.waitForSelector('[data-metric=edge]');
 assert.match(await page.locator('[data-metric=edge]').innerText(),/手入力/);
 await page.locator('[data-edit=edge]').click();await page.locator('#clear-manual').click();
 assert.match(await page.locator('[data-metric=edge]').innerText(),/残量を確認できません/);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Mobile page overflows horizontally');
 await page.screenshot({path:'test-output/usage/mobile.png',fullPage:true});
 await page.unroute('**/rest/v1/resource_usage_public?**');
 await page.route('**/rest/v1/resource_usage_public?**',route=>route.abort());
 await page.locator('#refresh').click();
 await page.waitForFunction(()=>document.getElementById('notice').textContent.includes('Supabaseの取得に失敗'));
 assert.match(await page.locator('[data-metric=db]').innerText(),/残り 460 MB/,'Transient errors must preserve timestamped data');
 await page.reload();await page.waitForFunction(()=>document.getElementById('notice').textContent.includes('Supabaseの取得に失敗'));
 assert.match(await page.locator('[data-metric=db]').innerText(),/残量を確認できません/,'Unknown usage must not become zero');
 assert.equal(errors.length,0,errors.join('\n'));
 console.log('Usage browser: desktop/mobile, real public build report, isolated provider fixtures, manual overage/persistence/delete, dialog keyboard and partial failures passed.');
 await context.close();
}finally{await browser.close();}
