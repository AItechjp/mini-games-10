import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {mkdir} from 'node:fs/promises';
await mkdir('test-output/government-network',{recursive:true});
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173/commons/government-network/');
 await page.locator('#download').waitFor({state:'visible'});
 await page.waitForFunction(()=>!document.getElementById('download').disabled);
 await page.selectOption('#kind','iaa');
 assert.equal(await page.locator('#result-count strong').innerText(),'86');
 await page.selectOption('#page-size','10000');
 assert.ok(await page.locator('#world .node').count()>=86);
 await page.selectOption('#page-size','8');
 await page.fill('#search','理化学研究所');
 assert.equal(await page.locator('#result-count strong').innerText(),'1');
 await page.click('#list-view');
 await page.locator('#table-view button').click();
 assert.match(await page.locator('#detail').innerText(),/理化学研究所/);
 assert.ok(await page.locator('#detail a.source').count()>0);
 await page.screenshot({path:'test-output/government-network/government-desktop.png'});
 await page.goto('http://127.0.0.1:4173/commons/reemployment-network/');
 await page.waitForFunction(()=>!document.getElementById('download').disabled);
 assert.equal(await page.locator('#result-count strong').innerText(),'1,753');
 await page.selectOption('#kind','special');
 assert.equal(await page.locator('#result-count strong').innerText(),'20');
 await page.fill('#search','山田滝雄');
 assert.equal(await page.locator('#result-count strong').innerText(),'2');
 await page.click('#list-view');
 await page.locator('#table-view button').first().click();
 assert.match(await page.locator('#detail').innerText(),/原資料に記載なし/);
 await page.screenshot({path:'test-output/government-network/reemployment-desktop.png'});
 await page.selectOption('#kind','career');
 assert.equal(await page.locator('#result-count strong').innerText(),'0');
 await page.locator('#graph-empty').waitFor({state:'visible'});
 await page.setViewportSize({width:393,height:852});
 await page.goto('http://127.0.0.1:4173/commons/government-network/');
 await page.waitForFunction(()=>!document.getElementById('download').disabled);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await page.screenshot({path:'test-output/government-network/government-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: integrated 86-IAA atlas, 1753 records, duplicate-person jobs, evidence links, career unknowns and mobile layout.');
} finally {await browser.close();}
