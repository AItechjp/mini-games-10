import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFile,realpath,mkdir,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
const require=createRequire(import.meta.url);
const esbuild=createRequire(await realpath('node_modules/vite/package.json'))('esbuild');
const out=resolve('work/commercial-tests');await mkdir(out,{recursive:true});
await esbuild.build({stdin:{contents:"export * from './lib/weather-provider';export * from './lib/weather';export * from './edge/origins';export * from './lib/sauna-status';export * from './lib/local-data';",resolveDir:process.cwd()},outfile:join(out,'commercial.cjs'),bundle:true,platform:'node',format:'cjs',logLevel:'silent'});
process.env.TZ='UTC';
const {weatherProviderUrl,weatherCities,allowedOrigins,serviceHosts,saunaStatus,parseLocalSnapshot}=require(join(out,'commercial.cjs'));
assert.equal(serviceHosts.length,17);
for(const host of serviceHosts)assert(allowedOrigins.has(`https://${host}.aitechd.com`));
for(const bad of ['http://sauna.aitechd.com','https://sauna.aitechd.com.evil.example','https://evil.aitechd.com','null','https://aitechd.com:8443'])assert(!allowedOrigins.has(bad));
assert.throws(()=>weatherProviderUrl(weatherCities[0],{commercial:true}));
const paid=weatherProviderUrl(weatherCities[0],{commercial:true,apiKey:'test-only-not-a-real-key'});
assert.equal(paid.hostname,'customer-api.open-meteo.com');assert.equal(paid.searchParams.get('apikey'),'test-only-not-a-real-key');
assert.equal(weatherProviderUrl(weatherCities[0]).hostname,'api.open-meteo.com');
const snapshot=JSON.parse(await readFile('data/sauna-snapshot.json','utf8'));
const closed=snapshot.facilities.find(f=>f.id==='node/6816287185');
assert.equal(saunaStatus(closed,Date.parse('2026-09-13T12:00:00+09:00')).state,'closed');
assert.match(saunaStatus(closed,Date.parse('2026-09-13T12:00:00+09:00')).reason,/閉店/);
const temporary=snapshot.facilities.find(f=>f.id==='node/9136959916');
assert.match(saunaStatus(temporary,Date.parse('2026-10-27T00:00:00+09:00')).reason,/休館/);
assert.doesNotMatch(saunaStatus(temporary,Date.parse('2026-10-26T23:59:59+09:00')).reason??'',/休館/);
assert.doesNotMatch(saunaStatus(temporary,Date.parse('2026-10-28T00:00:00+09:00')).reason??'',/休館/);
assert.equal(saunaStatus(snapshot.facilities.find(f=>f.id==='way/721575992'),Date.parse('2026-09-13T16:00:00+09:00')).state,'unknown');
assert.ok(Number.isFinite(Date.parse(snapshot.fetchedAt)));assert.match(snapshot.revision,/^[a-f0-9]{16}$/);
const local=JSON.parse(await readFile('public/local-data.json','utf8'));
assert.equal(parseLocalSnapshot(local),local);
assert.throws(()=>parseLocalSnapshot({...local,stores:[local.stores[0],local.stores[0]]}));
assert.throws(()=>parseLocalSnapshot({...local,stores:[{...local.stores[0],categories:null}]}));
assert.throws(()=>parseLocalSnapshot({...local,stores:[{...local.stores[0],note:{}}]}));
assert.throws(()=>parseLocalSnapshot({...local,updatedAt:'not-a-date'}));
assert.ok(!local.stores.some(s=>/^市/.test(s.city)));
const g=local.stores.filter(s=>s.address.startsWith('愛知県蒲郡市'));assert(g.length>=6);assert(g.every(s=>s.city==='蒲郡市'||!s.city));
const result={passed:true,serviceOrigins:17,rejectedOrigins:5,commercialWeatherConfiguration:true,officialClosureAndJstBoundaries:true,cityCorrection:true};
await writeFile(join(out,'commercial-result.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
