import assert from 'node:assert/strict';
import {readFile,realpath} from 'node:fs/promises';
import {createRequire} from 'node:module';
const {build}=createRequire(await realpath('node_modules/vite/package.json'))('esbuild');
await build({stdin:{contents:"export {combineFacilities,facilityState} from './aitech/sauna-nationwide';export {localStatus} from './lib/local-hours';export {prefectures} from './lib/sauna-types'",resolveDir:process.cwd(),loader:'ts'},outfile:'/tmp/sauna-national-test.mjs',platform:'node',format:'esm',bundle:true,loader:{'.css':'empty'}});
const {combineFacilities,facilityState,localStatus,prefectures}=await import('/tmp/sauna-national-test.mjs');
const facilities=JSON.parse(await readFile('data/sauna-nationwide.json'));
assert.equal(new Set(facilities.map(s=>s.id)).size,facilities.length);
assert.equal(new Set(facilities.map(s=>s.prefecture)).size,47);
for(const p of prefectures)assert.ok(facilities.filter(s=>s.prefecture===p).length>=2,p);
const now=Date.parse('2026-09-19T12:00:00+09:00');
for(const f of facilities){assert.ok(f.hours&&f.address&&f.sourceUrl&&Number.isFinite(Date.parse(f.checkedAt)),f.name);assert.ok(!/不明|未確認|未登録/.test(f.hoursText||''),f.name);if(!f.manualCalendar)assert.notEqual(localStatus(f,now).state,'unknown',f.name+' '+f.hours);}
const sample={...facilities[0],hours:'10:00-26:00',checkedAt:'2026-09-19T00:00:00+09:00',lastEntry:1500,closurePeriods:[],exceptions:{},manualCalendar:false};
const at=s=>Date.parse(s+'+09:00');
assert.equal(facilityState(sample,at('2026-09-20T00:59:00')),'open');
assert.equal(facilityState(sample,at('2026-09-20T01:00:00')),'reception-ended');
assert.equal(facilityState(sample,at('2026-09-20T02:00:00')),'closed');
assert.equal(facilityState({...sample,hours:'05:00-09:00,10:00-26:00'},at('2026-09-20T07:00:00')),'open');
assert.equal(facilityState({...sample,manualCalendar:true,exceptions:{'2026-09-20':'off'}},at('2026-09-20T15:00:00')),'closed');
const hana=facilities.find(s=>s.name.includes('華のゆ'));
assert.equal(facilityState(hana,at('2026-10-01T12:00:00')),'closed');
const kagomma=facilities.find(s=>s.name==='かごっま温泉');
assert.equal(facilityState(kagomma,at('2026-09-25T12:00:00')),'closed');
const yulax=facilities.find(s=>s.name==='湯らっくす');
assert.equal(facilityState(yulax,at('2026-11-18T12:00:00')),'closed');
assert.equal(facilityState(yulax,at('2026-11-20T16:00:00')),'closed');
assert.equal(facilityState(yulax,at('2026-11-20T18:00:00')),'open');
const live={...sample,kinds:['sauna'],lastEntry:1410,lastEntryBeforeClose:undefined,checkedAt:'2026-09-19T11:50:00+09:00',expiresAt:'2026-09-19T13:50:00+09:00'};
assert.equal(combineFacilities([{...sample,lastEntryBeforeClose:60}],[live],now)[0].lastEntryBeforeClose,undefined);
assert.equal(combineFacilities([sample],[{...live,expiresAt:'2026-09-19T10:00:00+09:00'}],now)[0].checkedAt,sample.checkedAt);
console.log(`Verified ${facilities.length} facilities, all 47 prefectures, source completeness, schedules, overnight admission and merge freshness.`);
